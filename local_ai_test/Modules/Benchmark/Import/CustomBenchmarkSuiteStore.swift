//  local_ai_test
//
//  Suites the user brought in, kept next to the bundled one.
//
//  One JSON file per suite under Application Support, the same shape
//  `BenchmarkReportStore` uses for reports and for the same reason: a
//  corrupted file costs one suite, not the whole list. Application Support
//  rather than Documents because a suite is app state, not user output — it
//  was already handed to us as a file the user has their own copy of.
//
//  The stored envelope keeps where the suite came from and when it arrived,
//  so a run's report can still name the suite that graded it after the file
//  has been deleted.
//

import Foundation
import Observation

// MARK: - Stored suite

nonisolated struct StoredBenchmarkSuite: Codable, Sendable, Hashable, Identifiable {

    /// Also `BenchmarkSuiteDocument.identity` of `document`, and what a
    /// report stores in `QualityResults.suiteID`.
    let id: String
    let name: String
    /// Filename or URL the suite was read from, shown in the list.
    let source: String
    let format: SuiteImportFormat
    let importedAt: Date
    let document: BenchmarkSuiteDocument

    var taskCount: Int { document.tasks.count }

    init(
        id: String,
        name: String,
        source: String,
        format: SuiteImportFormat,
        importedAt: Date = Date(),
        document: BenchmarkSuiteDocument
    ) {
        self.id = id
        self.name = name
        self.source = source
        self.format = format
        self.importedAt = importedAt
        self.document = document
    }
}

// MARK: - On-disk

nonisolated enum CustomBenchmarkSuiteFile {

    /// A fresh suite id. Prefixed so an id can never be mistaken for
    /// `BenchmarkSuiteDocument.builtInID` in a stored report.
    static func newID() -> String {
        "custom-" + UUID().uuidString.lowercased().prefix(8)
    }

    static var directory: URL? {
        guard let base = FileManager.default.urls(
            for: .applicationSupportDirectory, in: .userDomainMask
        ).first else { return nil }
        let dir = base.appendingPathComponent("CustomBenchmarkSuites", isDirectory: true)
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        return dir
    }

    private static func makeEncoder() -> JSONEncoder {
        let encoder = JSONEncoder()
        encoder.outputFormatting = [.prettyPrinted, .sortedKeys]
        encoder.dateEncodingStrategy = .iso8601
        return encoder
    }

    private static func makeDecoder() -> JSONDecoder {
        let decoder = JSONDecoder()
        decoder.dateDecodingStrategy = .iso8601
        return decoder
    }

    /// Ids are generated by `newID()`, but a file dropped in by hand could
    /// carry anything, so the path component is sanitised before it is used.
    private static func filename(for id: String) -> String {
        let safe = id.map { $0.isLetter || $0.isNumber || $0 == "-" ? $0 : "-" }
        return String(safe) + ".json"
    }

    static func save(_ suite: StoredBenchmarkSuite) throws {
        guard let directory else {
            throw SuiteImportError.storageUnavailable
        }
        let data = try makeEncoder().encode(suite)
        try data.write(
            to: directory.appendingPathComponent(filename(for: suite.id)),
            options: .atomic
        )
    }

    static func load(id: String) -> StoredBenchmarkSuite? {
        guard let directory else { return nil }
        let url = directory.appendingPathComponent(filename(for: id))
        guard let data = try? Data(contentsOf: url) else { return nil }
        return try? makeDecoder().decode(StoredBenchmarkSuite.self, from: data)
    }

    /// Every readable suite, newest import first. Unreadable files are
    /// skipped rather than fatal.
    static func list() -> [StoredBenchmarkSuite] {
        guard let directory else { return [] }
        let urls = (try? FileManager.default.contentsOfDirectory(
            at: directory, includingPropertiesForKeys: nil, options: [.skipsHiddenFiles]
        )) ?? []
        let decoder = makeDecoder()
        return urls
            .filter { $0.pathExtension == "json" }
            .compactMap { try? decoder.decode(StoredBenchmarkSuite.self, from: Data(contentsOf: $0)) }
            .sorted { $0.importedAt > $1.importedAt }
    }

    static func delete(id: String) {
        guard let directory else { return }
        try? FileManager.default.removeItem(
            at: directory.appendingPathComponent(filename(for: id))
        )
    }
}

// MARK: - Observable store

@MainActor
@Observable
final class CustomBenchmarkSuiteStore {

    static let shared = CustomBenchmarkSuiteStore()

    private(set) var suites: [StoredBenchmarkSuite] = []

    init() {
        reload()
    }

    func reload() {
        suites = CustomBenchmarkSuiteFile.list()
    }

    func add(_ suite: StoredBenchmarkSuite) throws {
        try CustomBenchmarkSuiteFile.save(suite)
        reload()
    }

    func delete(_ suite: StoredBenchmarkSuite) {
        CustomBenchmarkSuiteFile.delete(id: suite.id)
        reload()
    }

    func suite(id: String) -> StoredBenchmarkSuite? {
        suites.first { $0.id == id }
    }
}
